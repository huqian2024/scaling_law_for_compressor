#!/usr/bin/env python
"""02_generate_geometry.py — Phase 2 orchestration layer (stdlib only).

Pipeline::

    production CSV
      -> global validation / case selection
      -> geometry_legacy_v1 pure core (candidate bytes in memory)
      -> candidate vs existing comparison
      -> safe filesystem actions (atomic single-file writes)
      -> machine-readable JSONL reporting
      -> frozen exit-code semantics

This module contains NO geometry mathematics. It only orchestrates the pure core
``code/geometry_legacy_v1.py``.

Contract: ``docs/GEOMETRY_GENERATOR_CONTRACT.md`` (FROZEN V1).

Notes:
* ``--resume`` does not exist; resume is the default behavior via ``SKIP_MATCH``.
* ``--config`` is intentionally absent in v1.
* ``--dry-run`` guarantees that the project tree is unchanged.
"""

import argparse
import csv
import hashlib
import json
import math
import os
import re
import sys
import tempfile
from pathlib import Path

CODE_DIR = Path(__file__).resolve().parent
if str(CODE_DIR) not in sys.path:
    sys.path.insert(0, str(CODE_DIR))

import geometry_legacy_v1 as geo  # noqa: E402

CASE_ID_RE = re.compile(r"^C[0-9]{6}$")

REQUIRED_COLUMNS = [
    "case_id", "Xthick", "Tmax", "Metal2", "Solidity", "Incidence", "Mach",
    "range_id", "sampling_id",
]
NUMERIC_COLUMNS = ["Xthick", "Tmax", "Metal2", "Solidity", "Incidence", "Mach"]

# Frozen action vocabulary (see contract section 7).
CREATE = "CREATE"
SKIP_MATCH = "SKIP_MATCH"
CONFLICT_PARTIAL = "CONFLICT_PARTIAL"
CONFLICT_CONTENT = "CONFLICT_CONTENT"
WOULD_OVERWRITE = "WOULD_OVERWRITE"
OVERWRITE = "OVERWRITE"
ERROR = "ERROR"

# Frozen exit codes (see contract section 9).
EXIT_OK = 0
EXIT_CLI = 2
EXIT_CONFLICT = 3
EXIT_ERROR = 4


class CliError(Exception):
    """CLI / input contract failure -> exit code 2."""


def _atomic_write_bytes(path: Path, data: bytes) -> None:
    """Write ``data`` to ``path`` atomically.

    The temp file is created in the *same directory* as the target so that
    ``os.replace`` is an atomic rename on the same filesystem.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        dir=str(path.parent), prefix=".tmp-" + path.name + "-", suffix=".part")
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp_path, path)
    except BaseException:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise


def _emit(obj) -> None:
    sys.stdout.write(json.dumps(obj, sort_keys=True) + "\n")


def _load_template(path: Path):
    """Return (template_text, sha256_of_raw_bytes). Never modifies the file.

    The SHA256 is computed over the **raw** bytes (no newline translation).

    The generation text is decoded and then newline-normalized explicitly, to
    replicate the legacy script's text-mode read (``open(..., 'r')`` uses
    universal newlines). The legacy GT_V1 template is stored with CRLF line
    endings, while the frozen ``legacy_geometry_v1`` oracle is LF; without this
    explicit normalization the generated bytes would not match the oracle.
    This normalization is deliberate and documented, not silent.
    """
    if not path.is_file():
        raise CliError(f"template not found or not a file: {path}")
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise CliError(f"template unreadable: {path}: {exc}")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise CliError(f"template is not valid UTF-8: {path}: {exc}")
    sha256 = hashlib.sha256(raw).hexdigest()
    # Legacy text-mode read semantics (universal newlines).
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return text, sha256


def _load_and_validate_csv(path: Path):
    """Read and fully validate the input CSV. Raises CliError on any violation."""
    if not path.is_file():
        raise CliError(f"input CSV not found or not a file: {path}")
    try:
        with open(path, newline="") as f:
            reader = csv.DictReader(f)
            fieldnames = list(reader.fieldnames or [])
            rows = list(reader)
    except OSError as exc:
        raise CliError(f"input CSV unreadable: {path}: {exc}")

    missing = [c for c in REQUIRED_COLUMNS if c not in fieldnames]
    if missing:
        raise CliError("input CSV missing required column(s): " + ", ".join(missing))

    if not rows:
        raise CliError("input CSV has no data rows")

    seen = set()
    for lineno, row in enumerate(rows, start=2):
        cid = (row.get("case_id") or "").strip()
        if not CASE_ID_RE.match(cid):
            raise CliError(
                f"row {lineno}: invalid case_id {cid!r} "
                "(expected pattern: C followed by 6 digits)")
        if cid in seen:
            raise CliError(f"row {lineno}: duplicate case_id {cid!r}")
        seen.add(cid)

        for col in NUMERIC_COLUMNS:
            raw = row.get(col)
            try:
                val = float(raw)
            except (TypeError, ValueError):
                raise CliError(f"row {lineno} ({cid}): {col}={raw!r} is not a float")
            if not math.isfinite(val):
                raise CliError(f"row {lineno} ({cid}): {col}={raw!r} is not finite")

        xthick = float(row["Xthick"])
        if not (0.0 < xthick < 1.0):
            raise CliError(
                f"row {lineno} ({cid}): Xthick must satisfy 0 < Xthick < 1, "
                f"got {xthick!r}")
        solidity = float(row["Solidity"])
        if solidity <= 0.0:
            raise CliError(
                f"row {lineno} ({cid}): Solidity must be > 0, got {solidity!r}")
    return rows


def _select_rows(rows, requested_case_ids):
    """Select rows by case_id, always preserving original CSV row order."""
    if not requested_case_ids:
        return list(rows)
    requested = set(requested_case_ids)          # de-duplicate CLI repeats
    available = {(r.get("case_id") or "").strip() for r in rows}
    missing = sorted(requested - available)
    if missing:
        raise CliError(
            "requested --case-id not present in input CSV: " + ", ".join(missing))
    return [r for r in rows if (r.get("case_id") or "").strip() in requested]


def _output_paths(output_root: Path, case_id: str):
    return (output_root / "profiles" / f"{case_id}.dat",
            output_root / "geomturbo" / f"{case_id}.geomTurbo")


def _classify(profile_path: Path, geom_path: Path, cand_profile, cand_geom):
    p_exists = profile_path.is_file()
    g_exists = geom_path.is_file()
    if not p_exists and not g_exists:
        return CREATE
    if p_exists and g_exists:
        try:
            if (profile_path.read_bytes() == cand_profile
                    and geom_path.read_bytes() == cand_geom):
                return SKIP_MATCH
        except OSError:
            return CONFLICT_CONTENT
        return CONFLICT_CONTENT
    return CONFLICT_PARTIAL


def _decide(base_action, dry_run, overwrite):
    if base_action == SKIP_MATCH:
        return SKIP_MATCH
    if base_action in (CONFLICT_PARTIAL, CONFLICT_CONTENT):
        if not overwrite:
            return base_action
        return WOULD_OVERWRITE if dry_run else OVERWRITE
    return CREATE  # base_action == CREATE


def _reason_for(action, dry_run):
    if action == CREATE:
        return "outputs would be created" if dry_run else "outputs created"
    if action == SKIP_MATCH:
        return "existing outputs already match candidate"
    if action == CONFLICT_PARTIAL:
        return "only one of profile/geomTurbo exists; no overwrite"
    if action == CONFLICT_CONTENT:
        return "existing outputs differ from candidate; no overwrite"
    if action == WOULD_OVERWRITE:
        return "partial/content conflict would be overwritten (dry-run)"
    if action == OVERWRITE:
        return "replaced mismatching outputs"
    return ""


def _detect_obstruction(output_root: Path, profile_path: Path, geom_path: Path):
    """Deterministic, read-only detection of an output-path obstruction.

    Uses filesystem metadata only (no mkdir, no temp files, no probing writes), so
    it is equally valid under ``--dry-run`` (contract V1.2, section 18).
    Returns a non-empty reason string, or ``None`` when unobstructed.
    """
    for d in (output_root, output_root / "profiles", output_root / "geomturbo"):
        if d.is_file():
            return f"output path obstruction: {d} exists as a regular file"
    if profile_path.is_dir():
        return f"output path obstruction: {profile_path} exists as a directory"
    if geom_path.is_dir():
        return f"output path obstruction: {geom_path} exists as a directory"
    return None


def _process_row(row, args, output_root: Path, template_text: str):
    """Generate the candidate, classify it, and apply the filesystem action."""
    case_id = (row.get("case_id") or "").strip()
    profile_path, geom_path = _output_paths(output_root, case_id)

    obstruction = _detect_obstruction(output_root, profile_path, geom_path)
    if obstruction is not None:
        return case_id, profile_path, geom_path, ERROR, obstruction

    try:
        profile_text, geomturbo_text = geo.generate_geometry_texts(
            float(row["Xthick"]), float(row["Tmax"]), float(row["Metal2"]),
            float(row["Solidity"]), template_text)
        cand_profile = profile_text.encode("utf-8")
        cand_geom = geomturbo_text.encode("utf-8")
    except Exception as exc:  # noqa: BLE001 - a per-case failure must not abort the batch
        return (case_id, profile_path, geom_path, ERROR,
                f"geometry generation failed: {exc.__class__.__name__}: {exc}")

    base = _classify(profile_path, geom_path, cand_profile, cand_geom)
    action = _decide(base, args.dry_run, args.overwrite)

    if action in (CREATE, OVERWRITE) and not args.dry_run:
        # Pair-level transaction is intentionally not provided in v1: profile is
        # written first, geomTurbo second. A crash or I/O failure between the two
        # writes is surfaced as ERROR for this case (never a false CREATE/OVERWRITE
        # success) and is recovered on the next run as CONFLICT_PARTIAL /
        # CONFLICT_CONTENT.
        try:
            _atomic_write_bytes(profile_path, cand_profile)
            _atomic_write_bytes(geom_path, cand_geom)
        except Exception as exc:  # noqa: BLE001 - per-case I/O failure must not abort batch
            return (case_id, profile_path, geom_path, ERROR,
                    f"filesystem write failed: {exc.__class__.__name__}: {exc}")

    return case_id, profile_path, geom_path, action, _reason_for(action, args.dry_run)


def run(args):
    input_path = Path(args.input)
    template_path = Path(args.template)
    output_root = Path(args.output)

    # Full input validation happens before any output is written.
    rows = _load_and_validate_csv(input_path)
    template_text, template_sha256 = _load_template(template_path)
    selected = _select_rows(rows, args.case_ids)

    counts = {"create": 0, "skip": 0, "overwrite": 0, "conflict": 0,
              "would_overwrite": 0, "error": 0}

    for row in selected:
        case_id, pp, gp, action, reason = _process_row(
            row, args, output_root, template_text)
        _emit({
            "type": "case",
            "case_id": case_id,
            "action": action,
            "profile_path": str(pp),
            "geomturbo_path": str(gp),
            "reason": reason,
        })
        if action == CREATE:
            counts["create"] += 1
        elif action == SKIP_MATCH:
            counts["skip"] += 1
        elif action == OVERWRITE:
            counts["overwrite"] += 1
        elif action in (CONFLICT_PARTIAL, CONFLICT_CONTENT):
            counts["conflict"] += 1
        elif action == WOULD_OVERWRITE:
            counts["would_overwrite"] += 1
        elif action == ERROR:
            counts["error"] += 1

    _emit({
        "type": "summary",
        "input_path": str(input_path),
        "output_path": str(output_root),
        "template_path": str(template_path),
        "template_sha256": template_sha256,
        "dry_run": bool(args.dry_run),
        "overwrite": bool(args.overwrite),
        "selected_count": len(selected),
        "create_count": counts["create"],
        "skip_match_count": counts["skip"],
        "overwrite_count": counts["overwrite"],
        "conflict_count": counts["conflict"],
        "would_overwrite_count": counts["would_overwrite"],
        "error_count": counts["error"],
        "predicted_conflict_count": counts["conflict"] + counts["would_overwrite"],
        "predicted_error_count": counts["error"],
    })

    if counts["error"] > 0:
        return EXIT_ERROR
    if counts["conflict"] > 0:
        return EXIT_CONFLICT
    return EXIT_OK


def build_parser():
    parser = argparse.ArgumentParser(
        prog="02_generate_geometry.py",
        description="Generate legacy-compatible profile/.geomTurbo for a design CSV.")
    parser.add_argument("--input", required=True, metavar="PATH",
                        help="input master design CSV")
    parser.add_argument("--template", required=True, metavar="PATH",
                        help=".geomTurbo template file")
    parser.add_argument("--output", required=True, metavar="PATH",
                        help="output root directory (profiles/ + geomturbo/)")
    parser.add_argument("--case-id", dest="case_ids", action="append", default=[],
                        metavar="CASE_ID", help="select case_id (repeatable)")
    parser.add_argument("--dry-run", action="store_true",
                        help="compute and report without writing anything")
    parser.add_argument("--overwrite", action="store_true",
                        help="replace partial/content conflicts")
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        return run(args)
    except CliError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_CLI


if __name__ == "__main__":
    sys.exit(main())
